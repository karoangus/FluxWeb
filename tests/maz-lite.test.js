'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const dir = path.join(__dirname, '..', 'extensions', 'maz-lite');
const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
assert.equal(manifest.manifest_version, 3);
assert.deepEqual(manifest.permissions, ['storage']);
assert.deepEqual(manifest.content_scripts[0].matches, ['https://biomaze.ir/*', 'https://*.biomaze.ir/*']);
for (const file of [...manifest.content_scripts[0].js, ...manifest.content_scripts[0].css, manifest.action.default_popup]) assert.ok(fs.existsSync(path.join(dir, file)), file);
const root = { attrs: {}, setAttribute(k,v) { this.attrs[k] = v; }, removeAttribute(k) { delete this.attrs[k]; } };
let change, getCallback, observerInstance;
const document = { documentElement: root };
const ctx = vm.createContext({ document, MutationObserver: class { constructor(cb) { this.cb=cb; observerInstance=this; } observe() { this.observing=true; } disconnect() { this.observing=false; } }, chrome: { runtime: {}, storage: { local: { get(k,cb) { getCallback=cb; } }, onChanged: { addListener(cb) { change=cb; } } } } });
vm.runInContext(fs.readFileSync(path.join(dir, 'settings.js'), 'utf8'), ctx);
vm.runInContext(fs.readFileSync(path.join(dir, 'content.js'), 'utf8'), ctx);
assert.deepEqual(root.attrs, {}, 'No effect before stored settings load');
getCallback({mazLiteSettings: {enabled:false}});
assert.deepEqual(root.attrs, {}, 'master switch off');
change({mazLiteSettings: {newValue: {enabled:true, animations:false, shadows:false}}}, 'local');
assert.equal(root.attrs['data-mazlite-animations'], undefined);
assert.equal(root.attrs['data-mazlite-shadows'], undefined);
for (const k of ['transitions','textshadows','blur','smoothscroll']) assert.equal(root.attrs['data-mazlite-'+k], 'on');
change({mazLiteSettings: {newValue: {enabled:false}}}, 'local');
assert.deepEqual(root.attrs, {});
change({mazLiteSettings: {newValue: {enabled:true}}}, 'sync');
assert.deepEqual(root.attrs, {}, 'ignore other storage areas');
// Root not ready: observer applies settings once and disconnects.
document.documentElement = null;
change({mazLiteSettings: {newValue: {enabled:true}}}, 'local');
assert.equal(observerInstance.observing, true);
document.documentElement = root;
observerInstance.cb();
assert.equal(observerInstance.observing, false);
assert.equal(Object.keys(root.attrs).length, 6);
// An event received before the asynchronous read must win over that stale read.
const ctx2 = vm.createContext({document:{documentElement:root}, MutationObserver: class {}, chrome:{runtime:{},storage:{local:{get(k,cb){getCallback=cb;}},onChanged:{addListener(cb){change=cb;}}}}});
vm.runInContext(fs.readFileSync(path.join(dir,'settings.js'),'utf8'),ctx2);
vm.runInContext(fs.readFileSync(path.join(dir,'content.js'),'utf8'),ctx2);
change({mazLiteSettings:{newValue:{enabled:false}}},'local');
getCallback({mazLiteSettings:{enabled:true}});
assert.deepEqual(root.attrs, {}, 'stale storage read must not override change event');
console.log('Maz Lite simulated settings, scope, and lifecycle tests passed.');
// Exercise popup loading, independent controls, master switch and reset with mocked DOM/storage.
const ids = ['enabled','animations','transitions','shadows','textShadows','blur','smoothScroll','reset','status'];
const elements = Object.fromEntries(ids.map(id => [id, {checked:false, disabled:false, textContent:'', handlers:{}, addEventListener(type, fn){this.handlers[type] = fn;}}]));
let popupRead, stored, pending;
const popupCtx = vm.createContext({document:{getElementById(id){return elements[id];}}, chrome:{runtime:{},storage:{local:{get(k,cb){popupRead=cb;},set(value,cb){stored=value; pending=cb;}}}}});
vm.runInContext(fs.readFileSync(path.join(dir,'settings.js'),'utf8'),popupCtx);
vm.runInContext(fs.readFileSync(path.join(dir,'popup.js'),'utf8'),popupCtx);
assert.equal(elements.enabled.disabled,true);
popupRead({});
assert.equal(elements.enabled.checked,true);
assert.equal(elements.animations.checked,true);
elements.animations.checked=false;
elements.animations.handlers.change();
assert.equal(stored.mazLiteSettings.animations,false);
assert.equal(elements.enabled.disabled,true);
pending();
assert.equal(elements.enabled.disabled,false);
elements.enabled.checked=false;
elements.enabled.handlers.change();
assert.equal(stored.mazLiteSettings.enabled,false);
assert.equal(stored.mazLiteSettings.animations,false);
pending();
elements.reset.handlers.click();
assert.equal(stored.mazLiteSettings.enabled,true);
assert.equal(stored.mazLiteSettings.animations,true);
pending();
assert.equal(elements.status.textContent,'ذخیره شد');
console.log('Maz Lite simulated popup tests passed.');
